const DEFAULT_SCRIPT_URL = 'https://script.google.com/macros/s/AKfycbx2xZLBZfbljD4IGaAox8TmdGSGE3D9YxzRon39HqXdgMI4y-j5gS9fuUBs9VrwTtrgzg/exec';

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Credentials', true);
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET,POST,OPTIONS');
  res.setHeader(
    'Access-Control-Allow-Headers',
    'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version'
  );

  if (req.method === 'OPTIONS') {
    res.status(200).end();
    return;
  }

  const SCRIPT_URL = process.env.GOOGLE_SHEET_API_URL || DEFAULT_SCRIPT_URL;

  // Handle POST (Update Item)
  if (req.method === 'POST') {
    try {
      const response = await fetch(SCRIPT_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(req.body)
      });
      const data = await response.json();
      return res.status(200).json(data);
    } catch (error) {
      console.error('Error posting to Google Sheet:', error);
      return res.status(500).json({ success: false, error: error.message });
    }
  }

  // Handle GET (Fetch all trip data)
  if (req.method === 'GET') {
    try {
      const response = await fetch(SCRIPT_URL, {
        method: 'GET',
        headers: { 'Accept': 'application/json' }
      });
      if (response.ok) {
        const sheetData = await response.json();
        if (sheetData && sheetData.itinerary && sheetData.itinerary.length > 0) {
          return res.status(200).json(sheetData);
        }
      }
    } catch (error) {
      console.warn('Failed to fetch from Google Sheet URL, falling back to local dataset:', error.message);
    }

    return res.status(200).json(getDefaultTripData());
  }

  return res.status(405).json({ error: 'Method not allowed' });
}

